from abc import ABC, abstractmethod
from typing import List, Optional
from veterinaria.domain.entities.servicio import Servicio

class ServicioRepository(ABC):
    @abstractmethod
    def listar(self) -> List[Servicio]: ...
    @abstractmethod
    def obtener_por_id(self, servicio_id: int) -> Optional[Servicio]: ...
    @abstractmethod
    def existe_nombre(self, nombre: str, excluir_id: Optional[int] = None) -> bool: ...
    @abstractmethod
    def esta_en_uso(self, servicio_id: int) -> bool: ...
    @abstractmethod
    def guardar(self, servicio: Servicio) -> Servicio: ...
    @abstractmethod
    def eliminar(self, servicio_id: int) -> bool: ...
