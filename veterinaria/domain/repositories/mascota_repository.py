from abc import ABC, abstractmethod
from typing import List, Optional
from veterinaria.domain.entities.mascota import Mascota

class MascotaRepository(ABC):
    @abstractmethod
    def listar(self) -> List[Mascota]: ...
    @abstractmethod
    def obtener_por_id(self, mascota_id: int) -> Optional[Mascota]: ...
    @abstractmethod
    def tiene_atenciones(self, mascota_id: int) -> bool: ...
    @abstractmethod
    def guardar(self, mascota: Mascota) -> Mascota: ...
    @abstractmethod
    def eliminar(self, mascota_id: int) -> bool: ...
