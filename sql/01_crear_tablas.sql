DROP TABLE IF EXISTS detalle_atencion
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS atenciones
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS servicios
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS mascotas
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS duenos
    CASCADE CONSTRAINTS PURGE;


-- ============================================================
-- ELIMINACION DE LAS TABLAS ANTERIORES DEL MANUAL
-- Esto evita mantener las tablas del ejemplo clientes/ventas.
-- ============================================================

DROP TABLE IF EXISTS detalle_venta
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS ventas
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS productos
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS categorias
    CASCADE CONSTRAINTS PURGE;

DROP TABLE IF EXISTS clientes
    CASCADE CONSTRAINTS PURGE;


-- ============================================================
-- TABLA: DUENOS
-- El RUT identifica de manera unica a cada dueno.
-- Oracle coloca automaticamente la fecha de registro.
-- ============================================================

CREATE TABLE duenos (
    rut VARCHAR2(12) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    telefono VARCHAR2(20),
    email VARCHAR2(100),
    direccion VARCHAR2(150),

    fecha_registro TIMESTAMP
        DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP)
        NOT NULL,

    CONSTRAINT pk_duenos
        PRIMARY KEY (rut),

    CONSTRAINT uq_duenos_email
        UNIQUE (email)
);


-- ============================================================
-- TABLA: MASCOTAS
-- Cada mascota pertenece a un dueno.
-- ============================================================

CREATE TABLE mascotas (
    id_mascota NUMBER(11)
        GENERATED BY DEFAULT ON NULL
        AS IDENTITY (NOCACHE),

    rut_dueno VARCHAR2(12) NOT NULL,
    nombre VARCHAR2(80) NOT NULL,
    especie VARCHAR2(30) NOT NULL,
    raza VARCHAR2(60),
    fecha_nacimiento DATE,
    sexo VARCHAR2(10),
    activo NUMBER(1)
        DEFAULT 1
        NOT NULL,

    CONSTRAINT pk_mascotas
        PRIMARY KEY (id_mascota),

    CONSTRAINT fk_mascotas_dueno
        FOREIGN KEY (rut_dueno)
        REFERENCES duenos (rut),

    CONSTRAINT ck_mascotas_especie
        CHECK (
            especie IN (
                'PERRO',
                'GATO',
                'AVE',
                'CONEJO',
                'OTRO'
            )
        ),

    CONSTRAINT ck_mascotas_sexo
        CHECK (
            sexo IS NULL
            OR sexo IN (
                'MACHO',
                'HEMBRA'
            )
        ),

    CONSTRAINT ck_mascotas_activo
        CHECK (activo IN (0, 1))
);


-- ============================================================
-- TABLA: SERVICIOS
-- Contiene los servicios de la clinica veterinaria.
-- ============================================================

CREATE TABLE servicios (
    id_servicio NUMBER(11)
        GENERATED BY DEFAULT ON NULL
        AS IDENTITY (NOCACHE),

    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(200),
    precio NUMBER(10,2) NOT NULL,

    activo NUMBER(1)
        DEFAULT 1
        NOT NULL,

    CONSTRAINT pk_servicios
        PRIMARY KEY (id_servicio),

    CONSTRAINT uq_servicios_nombre
        UNIQUE (nombre),

    CONSTRAINT ck_servicios_precio
        CHECK (precio >= 0),

    CONSTRAINT ck_servicios_activo
        CHECK (activo IN (0, 1))
);


-- ============================================================
-- TABLA: ATENCIONES
-- Entidad principal del sistema.
-- Cada atencion pertenece a una mascota.
-- Oracle coloca automaticamente la fecha.
-- ============================================================

CREATE TABLE atenciones (
    id_atencion NUMBER(11)
        GENERATED BY DEFAULT ON NULL
        AS IDENTITY (NOCACHE),

    id_mascota NUMBER(11) NOT NULL,

    fecha TIMESTAMP
        DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP)
        NOT NULL,

    motivo VARCHAR2(200) NOT NULL,
    diagnostico VARCHAR2(500),

    total NUMBER(12,2)
        DEFAULT 0
        NOT NULL,

    estado VARCHAR2(20)
        DEFAULT 'AGENDADA'
        NOT NULL,

    CONSTRAINT pk_atenciones
        PRIMARY KEY (id_atencion),

    CONSTRAINT fk_atenciones_mascota
        FOREIGN KEY (id_mascota)
        REFERENCES mascotas (id_mascota),

    CONSTRAINT ck_atenciones_total
        CHECK (total >= 0),

    CONSTRAINT ck_atenciones_estado
        CHECK (
            estado IN (
                'AGENDADA',
                'REALIZADA',
                'PAGADA',
                'CANCELADA'
            )
        )
);


-- ============================================================
-- TABLA: DETALLE_ATENCION
-- Relaciona una atencion con los servicios realizados.
--
-- No tiene un ID individual.
-- Su clave primaria esta compuesta por:
-- id_atencion + id_servicio.
--
-- Oracle calcula automaticamente el subtotal.
-- ============================================================

CREATE TABLE detalle_atencion (
    id_atencion NUMBER(11) NOT NULL,
    id_servicio NUMBER(11) NOT NULL,

    cantidad NUMBER(11) NOT NULL,

    precio_unitario NUMBER(10,2)
        NOT NULL,

    subtotal NUMBER(12,2)
        GENERATED ALWAYS AS (
            cantidad * precio_unitario
        ) VIRTUAL,

    CONSTRAINT pk_detalle_atencion
        PRIMARY KEY (
            id_atencion,
            id_servicio
        ),

    CONSTRAINT fk_detalle_atencion_atencion
        FOREIGN KEY (id_atencion)
        REFERENCES atenciones (id_atencion)
        ON DELETE CASCADE,

    CONSTRAINT fk_detalle_atencion_servicio
        FOREIGN KEY (id_servicio)
        REFERENCES servicios (id_servicio),

    CONSTRAINT ck_detalle_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_detalle_precio
        CHECK (precio_unitario >= 0)
);


-- ============================================================
-- INDICES PARA MEJORAR LAS BUSQUEDAS
-- ============================================================

CREATE INDEX ix_mascotas_dueno
    ON mascotas (rut_dueno);

CREATE INDEX ix_atenciones_mascota
    ON atenciones (id_mascota);

CREATE INDEX ix_detalle_servicio
    ON detalle_atencion (id_servicio);